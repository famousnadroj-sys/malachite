-- Reconcile the production username mapping and login-throttle storage from live catalogs.
-- The original username-login migration filenames are missing from the repository.
create table if not exists public.login_names (
  user_id uuid primary key references auth.users(id) on delete cascade,
  username text not null,
  created_at timestamptz not null default now()
);
create unique index if not exists login_names_username_lower_uidx
  on public.login_names(lower(username));

alter table public.login_names enable row level security;
-- Only the validated SECURITY DEFINER profile RPC writes mappings; the login
-- Edge Function reads them with service_role. Browser roles never touch this table.
revoke all on table public.login_names from public,anon,authenticated;
grant select on table public.login_names to service_role;
drop policy if exists "login names owner read" on public.login_names;
drop policy if exists "login names owner insert" on public.login_names;
drop policy if exists "login names owner update" on public.login_names;

create table if not exists public.username_login_attempts (
  id bigint generated by default as identity primary key,
  ip_hash text not null,
  attempted_at timestamptz not null default now()
);
create index if not exists username_login_attempts_ip_time_idx
  on public.username_login_attempts(ip_hash,attempted_at desc);

alter table public.username_login_attempts enable row level security;
revoke all on table public.username_login_attempts from public,anon,authenticated;
grant all on table public.username_login_attempts to service_role;
revoke all on sequence public.username_login_attempts_id_seq from public,anon,authenticated;
grant usage,select on sequence public.username_login_attempts_id_seq to service_role;
drop policy if exists username_login_attempts_service_manage on public.username_login_attempts;
create policy username_login_attempts_service_manage
on public.username_login_attempts for all to service_role
using (true) with check (true);
