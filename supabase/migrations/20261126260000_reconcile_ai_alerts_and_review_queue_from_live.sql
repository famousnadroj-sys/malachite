-- Reconcile the production AI settings, alert and human-review queue tables from live catalogs.
-- Singleton AI settings table. Fresh replay defaults briefings OFF to avoid unapproved API spend;
-- an existing production setting (currently enabled by the owner) is preserved.
create table if not exists public.malachite_ai_settings (
  id smallint primary key check (id=1),
  ai_briefings_enabled boolean not null default false,
  updated_at timestamptz not null default now()
);
insert into public.malachite_ai_settings(id,ai_briefings_enabled)
values(1,false)
on conflict(id) do nothing;
alter table public.malachite_ai_settings enable row level security;
revoke all on table public.malachite_ai_settings from public,anon,authenticated;
grant all on table public.malachite_ai_settings to service_role;

-- Original alert/review migration filenames are missing; this captures the verified final schema.
create table if not exists public.malachite_ai_alerts (
  id bigint generated by default as identity primary key,
  alert_key text not null unique,
  severity text not null check (severity in ('info','warning','critical')),
  title text not null,
  details jsonb not null default '{}'::jsonb,
  status text not null default 'open' check (status in ('open','resolved')),
  first_seen_at timestamptz not null default now(),
  last_seen_at timestamptz not null default now(),
  resolved_at timestamptz
);

create table if not exists public.malachite_ai_review_queue (
  id bigint generated by default as identity primary key,
  task_key text not null unique,
  task_type text not null check (task_type in ('payment_review','report_review','support_review')),
  record_id text not null,
  title text not null,
  risk_level text not null check (risk_level in ('low','medium','high')),
  status text not null default 'awaiting_human'
    check (status in ('awaiting_human','approved','rejected','completed')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  details jsonb not null default '{}'::jsonb
);
create index if not exists malachite_ai_review_queue_status_idx
  on public.malachite_ai_review_queue(status,created_at desc);

alter table public.malachite_ai_alerts enable row level security;
alter table public.malachite_ai_review_queue enable row level security;
revoke all on table public.malachite_ai_alerts,public.malachite_ai_review_queue
  from public,anon,authenticated;
grant all on table public.malachite_ai_alerts,public.malachite_ai_review_queue
  to service_role;
revoke all on sequence public.malachite_ai_alerts_id_seq,public.malachite_ai_review_queue_id_seq
  from public,anon,authenticated;
grant usage,select on sequence public.malachite_ai_alerts_id_seq,public.malachite_ai_review_queue_id_seq
  to service_role;
