-- Reconcile the live administrator allowlist and audit table from production catalogs.
-- Original 202611180003_admin_audit_private_media SQL is not tracked; this is the
-- reviewed final-state source for the admin allowlist/audit objects.
create schema if not exists private;
revoke all on schema private from public,anon;
grant usage on schema private to authenticated;

create table if not exists private.admins (
  user_id uuid primary key references auth.users(id) on delete cascade
);
alter table private.admins enable row level security;
revoke all on table private.admins from public,anon,authenticated,service_role;

create or replace function private.is_admin()
returns boolean
language sql
stable
security definer
set search_path to ''
as $function$
  select exists (
    select 1 from private.admins
    where user_id=(select auth.uid())
  )
$function$;
revoke all on function private.is_admin() from public,anon;
grant execute on function private.is_admin() to authenticated;

create table if not exists public.admin_actions (
  id bigint generated by default as identity primary key,
  admin_id uuid references auth.users(id) on delete set null,
  action text not null,
  cible uuid references auth.users(id) on delete set null,
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);
do $constraint$
begin
  if not exists (
    select 1 from pg_constraint
    where conrelid='public.admin_actions'::regclass
      and conname='admin_actions_cible_fkey'
  ) then
    alter table public.admin_actions
      add constraint admin_actions_cible_fkey
      foreign key (cible) references auth.users(id) on delete set null;
  end if;
end
$constraint$;

create index if not exists admin_actions_admin_idx on public.admin_actions(admin_id);
create index if not exists admin_actions_created_idx on public.admin_actions(created_at desc);

alter table public.admin_actions enable row level security;
revoke all on table public.admin_actions from public,anon,authenticated;
grant select on table public.admin_actions to authenticated;
grant all on table public.admin_actions to service_role;
revoke all on sequence public.admin_actions_id_seq from public,anon,authenticated;
grant usage,select on sequence public.admin_actions_id_seq to service_role;

drop policy if exists "admin lit le journal" on public.admin_actions;
create policy "admin lit le journal"
on public.admin_actions for select to authenticated
using ((select private.is_admin()));

-- Preserve AI admin audit rows while removing stale account identifiers on deletion.
alter table public.ai_manager_audit alter column admin_id drop not null;
update public.ai_manager_audit a
set admin_id=null
where admin_id is not null
  and not exists(select 1 from auth.users u where u.id=a.admin_id);
do $ai_audit_fk$
begin
  if not exists (
    select 1 from pg_constraint
    where conrelid='public.ai_manager_audit'::regclass
      and conname='ai_manager_audit_admin_id_fkey'
  ) then
    alter table public.ai_manager_audit
      add constraint ai_manager_audit_admin_id_fkey
      foreign key (admin_id) references auth.users(id) on delete set null;
  end if;
end
$ai_audit_fk$;

revoke all on sequence public.ai_manager_audit_id_seq from public,anon,authenticated;
grant usage,select on sequence public.ai_manager_audit_id_seq to service_role;
