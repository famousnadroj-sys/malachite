-- Disposable integration contract based on the live Malachite message schema
-- and policy/trigger definitions inspected read-only on 2026-11-24.
-- This is an isolated contract fixture, NOT a production migration.
begin;

create schema auth;
create schema private;
create role authenticated;

create function auth.uid() returns uuid
language sql stable
as $$ select nullif(current_setting('request.jwt.claim.sub', true), '')::uuid $$;

create table public.profiles (
  id uuid primary key
);

create table public.messages (
  id bigint generated by default as identity primary key,
  de uuid not null default auth.uid(),
  a uuid not null,
  texte text not null,
  created_at timestamptz default now(),
  media_url text,
  media_type text
);

create table public.user_notifications (
  id bigint generated by default as identity primary key,
  user_id uuid not null,
  kind text not null,
  category text not null,
  title text not null,
  body text not null,
  related_message_id bigint,
  related_user_id uuid,
  constraint user_notifications_user_message_unique unique (user_id, related_message_id)
);

create table public.message_receipts (
  message_id bigint not null references public.messages(id) on delete cascade,
  sender_id uuid not null,
  recipient_id uuid not null,
  delivered_at timestamptz not null default now(),
  read_at timestamptz,
  primary key (message_id, recipient_id)
);

create function private.is_suspended(uuid) returns boolean
language sql stable as $$ select false $$;
create function private.is_blocked_with(uuid) returns boolean
language sql stable as $$ select false $$;
create function private.est_premium(uuid) returns boolean
language sql stable as $$ select true $$;

create function public.limite_messages()
returns trigger language plpgsql security definer set search_path = ''
as $function$
declare n integer;
begin
  if new.de is distinct from (select auth.uid()) then
    raise exception 'sender_invalide';
  end if;
  if private.is_suspended(new.de) then
    raise exception 'compte_suspendu';
  end if;
  if private.is_blocked_with(new.a) then
    raise exception 'conversation_bloquee';
  end if;
  if new.media_url is not null or new.media_type is not null then
    if new.media_type in ('image','audio','video','document') then
      if new.media_url is null or new.media_url !~ ('^'||new.de::text||'/'||new.a::text||'/[A-Za-z0-9._-]{1,120}$') then
        raise exception 'media_invalide';
      end if;
    elsif new.media_type='call' then
      if new.media_url is null or new.media_url !~ '^https://meet[.]jit[.]si/Malachite[0-9a-f]{20,40}$' then
        raise exception 'media_invalide';
      end if;
    else
      raise exception 'media_invalide';
    end if;
  end if;
  if not private.est_premium(new.de) and not exists (
    select 1 from public.messages m
    where (m.de=new.de and m.a=new.a) or (m.de=new.a and m.a=new.de)
  ) then
    select count(distinct m.a) into n
    from public.messages m
    where m.de=new.de and m.created_at>=date_trunc('day',now())
      and not exists (
        select 1 from public.messages prior
        where prior.de=m.a and prior.a=m.de and prior.created_at<m.created_at
      );
    if n>=15 then raise exception 'limite_gratuite'; end if;
  end if;
  return new;
end;
$function$;

create function private.notify_new_member_message()
returns trigger language plpgsql security definer set search_path = ''
as $function$
begin
  if new.de is null or new.a is null or new.de = new.a or new.media_type = 'call' then
    return new;
  end if;
  insert into public.user_notifications(
    user_id, kind, category, title, body, related_message_id, related_user_id
  ) values (
    new.a, 'message_received', 'message', 'Nouveau message',
    'Tu as reçu un nouveau message.', new.id, new.de
  )
  on conflict (user_id, related_message_id)
    where related_message_id is not null do nothing;
  return new;
end;
$function$;

create trigger trg_limite before insert on public.messages
for each row execute function public.limite_messages();
create trigger trg_notify_new_member_message after insert on public.messages
for each row execute function private.notify_new_member_message();

alter table public.messages enable row level security;
alter table public.message_receipts enable row level security;
alter table public.user_notifications enable row level security;

create policy "envoyer un message" on public.messages
for insert to authenticated
with check (
  de = (select auth.uid()) and a <> (select auth.uid())
  and not private.is_blocked_with(a)
  and not private.is_suspended((select auth.uid()))
  and not private.is_suspended(a)
  and exists (select 1 from public.profiles p where p.id = messages.a)
);
create policy "lire ses messages" on public.messages
for select to authenticated
using (
  (de = (select auth.uid()) or a = (select auth.uid()))
  and not private.is_suspended((select auth.uid()))
  and not private.is_suspended(
    case when de = (select auth.uid()) then a else de end
  )
  and not private.is_blocked_with(
    case when de = (select auth.uid()) then a else de end
  )
);
create policy "participants read message receipts" on public.message_receipts
for select to authenticated
using ((select auth.uid()) = sender_id or (select auth.uid()) = recipient_id);
create policy "recipient marks read" on public.message_receipts
for update to authenticated
using ((select auth.uid()) = recipient_id)
with check (
  (select auth.uid()) = recipient_id
  and exists (
    select 1 from public.messages m
    where m.id = message_receipts.message_id
      and m.de = message_receipts.sender_id
      and m.a = message_receipts.recipient_id
  )
);
create policy "recipient records delivery" on public.message_receipts
for insert to authenticated
with check (
  (select auth.uid()) = recipient_id
  and exists (
    select 1 from public.messages m
    where m.id = message_receipts.message_id
      and m.de = message_receipts.sender_id
      and m.a = message_receipts.recipient_id
  )
);
create policy "user reads own notifications" on public.user_notifications
for select to authenticated using (user_id = (select auth.uid()));

grant usage on schema auth, private to authenticated;
grant execute on function auth.uid() to authenticated;
grant execute on function private.is_suspended(uuid) to authenticated;
grant execute on function private.is_blocked_with(uuid) to authenticated;
grant execute on function private.est_premium(uuid) to authenticated;
grant select on public.profiles to authenticated;
grant insert, select on public.messages to authenticated;
grant insert, select, update on public.message_receipts to authenticated;

insert into public.profiles(id) values
('00000000-0000-0000-0000-00000000000a'),
('00000000-0000-0000-0000-00000000000b'),
('00000000-0000-0000-0000-00000000000c');

-- Verify the live schema's legacy sender/recipient columns remain NOT NULL.
do $$
begin
  if (select is_nullable from information_schema.columns
      where table_schema='public' and table_name='messages' and column_name='de') <> 'NO'
     or (select is_nullable from information_schema.columns
      where table_schema='public' and table_name='messages' and column_name='a') <> 'NO' then
    raise exception 'legacy_message_pair_must_remain_required_during_compatibility';
  end if;
end $$;

-- A sends to B: trigger validates sender and creates exactly one notification.
set role authenticated;
select set_config('request.jwt.claim.sub','00000000-0000-0000-0000-00000000000a',true);
insert into public.messages(a,texte)
values ('00000000-0000-0000-0000-00000000000b','A vers B');
reset role;

do $$
begin
  if (select count(*) from public.user_notifications
      where user_id='00000000-0000-0000-0000-00000000000b') <> 1 then
    raise exception 'message_notification_trigger_contract_failed';
  end if;
end $$;

-- A cannot forge B as sender.
set role authenticated;
select set_config('request.jwt.claim.sub','00000000-0000-0000-0000-00000000000a',true);
do $$
begin
  begin
    insert into public.messages(de,a,texte)
    values ('00000000-0000-0000-0000-00000000000b',
            '00000000-0000-0000-0000-00000000000a','forged');
    raise exception 'forged_sender_was_accepted';
  exception when others then
    if sqlerrm = 'forged_sender_was_accepted' then raise; end if;
    if sqlerrm <> 'sender_invalide' then raise; end if;
  end;
end $$;
reset role;

-- Only A and B can read the A/B message; C cannot.
set role authenticated;
select set_config('request.jwt.claim.sub','00000000-0000-0000-0000-00000000000b',true);
do $$
begin
  if (select count(*) from public.messages) <> 1 then
    raise exception 'recipient_cannot_read_message';
  end if;
end $$;
reset role;

set role authenticated;
select set_config('request.jwt.claim.sub','00000000-0000-0000-0000-00000000000c',true);
do $$
begin
  if (select count(*) from public.messages) <> 0 then
    raise exception 'non_participant_read_message';
  end if;
end $$;
reset role;

-- B may record a receipt only for the exact A->B message.
set role authenticated;
select set_config('request.jwt.claim.sub','00000000-0000-0000-0000-00000000000b',true);
insert into public.message_receipts(message_id,sender_id,recipient_id)
select id,de,a from public.messages where texte='A vers B';
reset role;

do $$
begin
  if (select count(*) from public.message_receipts) <> 1 then
    raise exception 'message_receipt_contract_failed';
  end if;
end $$;

rollback;
