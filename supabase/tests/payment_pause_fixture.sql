do $$
begin
  if not exists(select 1 from pg_roles where rolname='authenticated') then create role authenticated nologin; end if;
  if not exists(select 1 from pg_roles where rolname='anon') then create role anon nologin; end if;
end
$$;

create schema auth;
create or replace function auth.uid()
returns uuid language sql stable
as $$ select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid $$;

create table public.profiles(id uuid primary key);
create table public.avis_match(user_id uuid not null, autre uuid not null, ok boolean not null default false);
create table public.statuts(user_id uuid primary key, premium_until timestamptz);
create table public.paiements(
  id bigint generated by default as identity primary key,
  user_id uuid not null,
  offre text not null,
  code text not null,
  operateur text not null,
  receipt_path text,
  statut text not null default 'attente',
  cible uuid,
  created_at timestamptz not null default now(),
  reviewed_at timestamptz
);
create unique index paiements_operator_reference_uidx on public.paiements(operateur,code);
create function public.traiter_paiement(pid bigint, accepter boolean) returns void language plpgsql as $body$ begin return; end $body$;
create function public.traiter_paiement(pid bigint, accepter boolean, raison text) returns void language plpgsql as $body$ begin return; end $body$;
revoke all on function public.traiter_paiement(bigint,boolean) from public,anon;
revoke all on function public.traiter_paiement(bigint,boolean,text) from public,anon;
grant execute on function public.traiter_paiement(bigint,boolean) to authenticated;
grant execute on function public.traiter_paiement(bigint,boolean,text) to authenticated;
grant select,insert,update,delete on public.paiements to authenticated;
grant select on public.profiles,public.avis_match,public.statuts to authenticated;
alter table public.paiements enable row level security;
create policy "declarer un paiement" on public.paiements
for insert to authenticated
with check (user_id=(select auth.uid()));
create policy "voir ses paiements" on public.paiements
for select to authenticated
using (user_id=(select auth.uid()));

